// Builds design tokens from DTCG JSON (tokens/*.json) into:
//   src/styles/tokens.css   CSS custom properties + typography utility classes
//   src/tokens/tokens.ts    Typed token paths, CSS var references and resolved values
//
// No dependencies. Run with `npm run tokens` (also runs before dev and build).
// Aliases ("{color.blue.500}") are emitted as var() references in CSS so the
// primitive -> semantic -> component chain stays live in the browser.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TIERS = ['primitive', 'semantic', 'component'];

/** @typedef {{ path: string[], type: string, value: unknown, description?: string, tier: string, extensions?: Record<string, unknown> }} Token */

/** @type {Map<string, Token>} */
const tokens = new Map();

function walk(node, path, inheritedType, tier) {
  const type = node.$type ?? inheritedType;
  if (Object.prototype.hasOwnProperty.call(node, '$value')) {
    const key = path.join('.');
    if (tokens.has(key)) throw new Error(`Duplicate token: ${key}`);
    if (!type) throw new Error(`Token without $type: ${key}`);
    tokens.set(key, { path, type, value: node.$value, description: node.$description, tier, extensions: node.$extensions });
    return;
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null) continue;
    walk(v, [...path, k], type, tier);
  }
}

for (const tier of TIERS) {
  walk(JSON.parse(readFileSync(join(root, 'tokens', `${tier}.json`), 'utf8')), [], undefined, tier);
}

const ALIAS = /^\{([^}]+)\}$/;
const varName = (key) => `--${key.replace(/\./g, '-')}`;
const isAlias = (v) => typeof v === 'string' && ALIAS.test(v);
const aliasKey = (v) => {
  const key = v.match(ALIAS)[1];
  if (!tokens.has(key)) throw new Error(`Unknown alias ${v}`);
  return key;
};

// ---- CSS value formatting (aliases become var()) ---------------------------
function cssRef(v) {
  return isAlias(v) ? `var(${varName(aliasKey(v))})` : String(v);
}
function fontFamily(v) {
  if (isAlias(v)) return cssRef(v);
  return (Array.isArray(v) ? v : [v]).map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
}
function shadowPart(s) {
  return `${s.inset ? 'inset ' : ''}${cssRef(s.offsetX)} ${cssRef(s.offsetY)} ${cssRef(s.blur)} ${cssRef(s.spread)} ${cssRef(s.color)}`;
}
function toCss(t) {
  const v = t.value;
  if (isAlias(v)) return cssRef(v);
  switch (t.type) {
    case 'fontFamily': return fontFamily(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'shadow': return (Array.isArray(v) ? v : [v]).map(shadowPart).join(', ');
    case 'gradient': {
      const angle = t.extensions?.angle ?? '180deg';
      return `linear-gradient(${angle}, ${v.map((s) => `${cssRef(s.color)} ${s.position * 100}%`).join(', ')})`;
    }
    case 'transition': return `${cssRef(v.duration)} ${cssRef(v.timingFunction)} ${cssRef(v.delay)}`;
    default: return String(v);
  }
}

// ---- Fully resolved values (for TS + docs) ---------------------------------
function resolve(v, type) {
  if (isAlias(v)) {
    const t = tokens.get(aliasKey(v));
    return resolve(t.value, t.type);
  }
  if (type === 'typography' || type === 'transition') {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolve(x)]));
  }
  if (type === 'shadow') {
    return (Array.isArray(v) ? v : [v]).map((s) => Object.fromEntries(Object.entries(s).map(([k, x]) => [k, resolve(x)])));
  }
  if (type === 'gradient') return v.map((s) => ({ ...s, color: resolve(s.color) }));
  return v;
}

// ---- Emit CSS --------------------------------------------------------------
const TYPO_PROPS = { fontFamily: 'font-family', fontSize: 'font-size', fontWeight: 'font-weight', lineHeight: 'line-height', letterSpacing: 'letter-spacing' };
const lines = [];
const typographyClasses = [];

for (const tier of TIERS) {
  lines.push(`\n  /* ${tier} */`);
  for (const [key, t] of tokens) {
    if (t.tier !== tier) continue;
    if (t.type === 'typography') {
      for (const [prop, cssProp] of Object.entries(TYPO_PROPS)) {
        const raw = t.value[prop];
        lines.push(`  ${varName(key)}-${cssProp}: ${prop === 'fontFamily' ? fontFamily(raw) : cssRef(raw)};`);
      }
      const name = key.replace(/^typography\./, '');
      typographyClasses.push(
        `.type-${name} {\n${Object.values(TYPO_PROPS).map((p) => `  ${p}: var(${varName(key)}-${p});`).join('\n')}\n}`
      );
      continue;
    }
    lines.push(`  ${varName(key)}: ${toCss(t)};`);
  }
}

const header = '/* Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit by hand. */\n';
const css = `${header}:root {${lines.join('\n')}\n}\n\n/* Typography utilities: one class per semantic typography token */\n${typographyClasses.join('\n\n')}\n`;
mkdirSync(join(root, 'src/styles'), { recursive: true });
writeFileSync(join(root, 'src/styles/tokens.css'), css);

// ---- Emit TS ---------------------------------------------------------------
const entries = [...tokens.entries()];
const ts = `${header.replace('/*', '//').replace(' */', '')}
export type TokenTier = 'primitive' | 'semantic' | 'component';
export type TokenType = ${[...new Set(entries.map(([, t]) => t.type))].map((x) => `'${x}'`).join(' | ')};

export interface TokenMeta {
  path: TokenPath;
  tier: TokenTier;
  type: TokenType;
  cssVar: string;
  aliasOf?: TokenPath;
  value: unknown;
  description?: string;
}

/** Every token path in the system. */
export const tokenPaths = [
${entries.map(([k]) => `  '${k}',`).join('\n')}
] as const;

export type TokenPath = (typeof tokenPaths)[number];

/** Semantic and component tokens only: the ones components are allowed to use. */
export type UsableTokenPath = Exclude<TokenPath, ${entries.filter(([, t]) => t.tier === 'primitive').length ? `'${entries.filter(([, t]) => t.tier === 'primitive').map(([k]) => k).join("' | '")}'` : 'never'}>;

/** Returns the CSS var() reference for a token, e.g. token('color.primary.default'). */
export function token(path: UsableTokenPath): string {
  return \`var(--\${path.replace(/\\./g, '-')})\`;
}

export const tokens: Record<TokenPath, TokenMeta> = {
${entries
  .map(([k, t]) => {
    const meta = {
      path: k,
      tier: t.tier,
      type: t.type,
      cssVar: varName(k),
      ...(isAlias(t.value) ? { aliasOf: aliasKey(t.value) } : {}),
      value: resolve(t.value, t.type),
      ...(t.description ? { description: t.description } : {}),
    };
    return `  '${k}': ${JSON.stringify(meta)},`;
  })
  .join('\n')}
} as Record<TokenPath, TokenMeta>;

/** Breakpoints as numbers (px) for use in scripts. CSS mirrors these as literals. */
export const breakpoints = {
${entries.filter(([k]) => k.startsWith('breakpoint.')).map(([k, t]) => `  ${k.split('.')[1]}: ${parseInt(t.value, 10)},`).join('\n')}
} as const;
`;
mkdirSync(join(root, 'src/tokens'), { recursive: true });
writeFileSync(join(root, 'src/tokens/tokens.ts'), ts);

const counts = TIERS.map((tier) => `${tier}: ${entries.filter(([, t]) => t.tier === tier).length}`).join(', ');
console.log(`Built ${tokens.size} tokens (${counts})`);
